/**
 * What a PROVIDER sends a customer through Wi-Mall (SERVICE-LISTINGS-PLAN L-14 … L-16, § C-5):
 * "Ask them to call me" and a free-text message. Both reach only a customer who opted in to
 * that provider's messages, and both carry the way out — "Stop messages from this business"
 * (`lc:<vendorId>:n`) — and the way to answer, which is the provider's OWN WhatsApp (L-16: a
 * reply never comes back through Wi-Mall).
 *
 * A separate catalogue from the customer one on purpose: these are not notifications about the
 * customer's account. They have no inbox row, no push and no e-mail, they go to ONE chat, and
 * their author is a third party. Routing them through the customer stack would give a provider
 * a door into the customer's inbox and e-mail.
 *
 * ── The template (call-me only) ──────────────────────────────────────────────
 * `customer_listing_call_me`, generated by `scripts/generate-whatsapp-templates.ts` like every
 * other. ⛔ **It has NO chat button, and cannot have one:** Meta refuses a template URL button
 * that opens WhatsApp ("Les liens directs vers WhatsApp ne sont pas autorisés pour les
 * boutons", code 100, measured 2026-11-07). The provider's number is in the TEXT instead, where
 * WhatsApp makes it tappable ("Chat with…" / "Call") — owner's choice the same day, over a
 * Wi-Mall forwarding link. Its one button is the opt-out quick reply. Inside the window and on
 * Telegram the message still carries the `https://wa.me/<digits>` link (`LISTING_MESSAGE_BUTTON_BASE`).
 * The free text has NO template by design: it is refused outside the 24-hour window (L-15).
 *
 * ⚠ Meta will probably file the call-me template as MARKETING (plan § WhatsApp templates):
 * dearer per message, and silently undelivered to a customer who opted out of marketing.
 */
export const LISTING_MESSAGE_SITUATIONS = ['listing.call_me', 'listing.provider_message'] as const;
export type ListingMessageSituation = (typeof LISTING_MESSAGE_SITUATIONS)[number];

interface Copy {
  subject: string;
  body: string;
}

interface ListingMessageEntry {
  base: Readonly<Record<Language, Copy>>;
  /** Null = in-window only (the free text). */
  template: { name: string; bodyParams: readonly string[] } | null;
}

/** The chat button's host. Fixed, not configurable: Meta bakes it into the approved template. */
export const LISTING_MESSAGE_BUTTON_BASE = 'https://wa.me';

