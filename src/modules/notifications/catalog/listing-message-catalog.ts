/** The opt-out tap token (§ C-3a). */
export function listingStopToken(vendorId: string): string {
  // From the builder that owns the grammar, never written by hand (`test:inapp-fulfilment` § 10).
  return listingConsentActionId(vendorId, false);
}

export function renderListingMessageText(situation: ListingMessageSituation, lang: Language, ctx: RenderContext): Copy {
  const base = LISTING_MESSAGE_CATALOG[situation].base[lang] ?? LISTING_MESSAGE_CATALOG[situation].base.en;
  return { subject: renderTemplate(base.subject, ctx), body: renderTemplate(base.body, ctx) };
}

export function listingMessageTemplateName(situation: ListingMessageSituation): string | null {
  return LISTING_MESSAGE_CATALOG[situation].template?.name ?? null;
}

export function renderListingMessageTemplateParams(situation: ListingMessageSituation, _lang: Language, ctx: RenderContext): string[] {
  const tpl = LISTING_MESSAGE_CATALOG[situation].template;
  return tpl ? tpl.bodyParams.map((p) => renderTemplate(p, ctx)) : [];
}

/**
 * The generator's view of a template URL button: none, for either situation. Meta refuses a
 * template button that opens WhatsApp (see the header), and these messages have no Wi-Mall page
 * to open. Kept as a function so the generator's per-audience contract stays uniform.
 */
export function renderListingMessageButton(
  _situation: ListingMessageSituation,
  _lang: Language,
  _ctx: RenderContext,
): null {
  return null;
}

/** The template's quick replies, after the URL button — the opt-out (L-14). */
export function listingMessageTemplateQuickReplyLabels(situation: ListingMessageSituation): Array<Record<string, string>> {
  return situation === 'listing.call_me' ? [{ ...LISTING_STOP_LABEL }] : [];
}
